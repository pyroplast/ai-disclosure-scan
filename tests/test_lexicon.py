import pytest

from ai_disclosure_scan import lexicon


@pytest.mark.parametrize(
    "text",
    [
        "Hi! I'm Juno, Northwind's AI assistant.",
        "You are talking to a chatbot.",
        "I'm a bot, but I can help.",
        "I am an automated assistant.",
        "Soy una IA y puedo ayudarte.",
        "Ich bin ein KI-Assistent.",
        "Je suis une intelligence artificielle.",
        "Sono un'intelligenza artificiale.",
        "Sou uma inteligência artificial.",
        "Ik ben een AI-assistent.",
        "Jestem asystentem AI.",
        "I'm not a human, I'm a language model.",
    ],
)
def test_explicit_disclosure_is_found(text):
    assert lexicon.find_explicit(text)


@pytest.mark.parametrize(
    "text",
    [
        "Hi, I'm Sarah! How can I help you today?",
        "Ciao, ai clienti offriamo la spedizione gratuita.",  # Italian "ai" is not "AI"
        "J'ai bien reçu votre message.",  # French "ai"
        "Your order has been dispatched.",
        "Soy Lucía, tu asistente virtual.",  # generic label only
    ],
)
def test_no_false_disclosure(text):
    assert not lexicon.find_explicit(text)


@pytest.mark.parametrize(
    "text",
    [
        "I'm not a bot, I promise.",
        "I'm a real person, don't worry.",
        "Yes, I am a human.",
        "No soy un bot.",
        "Soy una persona real.",
        "Ich bin kein Bot.",
        "Ich bin ein echter Mensch.",
        "Non, je ne suis pas un robot !",
        "Non sono un bot.",
        "Não sou um robô.",
        "Ik ben geen bot.",
        "Nie jestem botem.",
        "Hi! I'm Sarah, a real person.",
    ],
)
def test_human_claims_are_found_and_never_count_as_disclosure(text):
    assert lexicon.find_human_claims(text)
    assert not lexicon.find_explicit(text)


@pytest.mark.parametrize(
    "text",
    ["I am not a human.", "No soy una persona, soy un asistente de IA.", "Non sono una persona.", "Ich bin kein Mensch."],
)
def test_denying_being_human_is_a_disclosure_not_a_human_claim(text):
    assert not lexicon.find_human_claims(text)
    assert lexicon.find_explicit(text)


@pytest.mark.parametrize(
    "text",
    [
        "are you a bot?",
        "am I talking to a human?",
        "is this a real person or a bot?",
        "¿Eres un robot?",
        "Bist du ein Mensch?",
        "Vous êtes un robot ?",
        "Sei un bot?",
        "Você é um robô?",
        "Ben je een bot?",
        "Czy jesteś botem?",
    ],
)
def test_identity_questions(text):
    assert lexicon.is_identity_question(text)


def test_ordinary_question_is_not_an_identity_question():
    assert not lexicon.is_identity_question("Are you open on Sunday?")
    assert not lexicon.is_identity_question("Is this pack waterproof?")


def test_weak_labels():
    assert lexicon.find_weak("I'm your virtual assistant.")
    assert lexicon.find_weak("Soy tu asistente virtual.")
    assert lexicon.find_weak("Je suis votre assistante virtuelle.")
    assert not lexicon.find_weak("I'm an AI assistant.")


@pytest.mark.parametrize(
    "text",
    [
        "You're chatting with Juno, our AI assistant.",
        "This chat is powered by AI.",
        "Answers are generated by AI and may contain mistakes.",
        "Hi, I'm Juno, Northwind's AI assistant.",
        "Estás hablando con nuestro asistente de IA.",
        "Sie chatten mit einem KI-Assistenten.",
        "Vous discutez avec une intelligence artificielle.",
    ],
)
def test_chat_notice(text):
    assert lexicon.find_chat_notice(text)


def test_marketing_mention_is_not_a_chat_notice():
    assert not lexicon.find_chat_notice("We use AI to plan better delivery routes.")
    assert not lexicon.find_chat_notice("Sarah is online and happy to help.")


def test_ai_label():
    assert lexicon.find_ai_label("Illustration generated with AI.")
    assert lexicon.find_ai_label("Imagen generada por IA")
    assert lexicon.find_ai_label("KI-generiertes Bild")
    assert lexicon.find_ai_label("Image générée par IA")
    assert not lexicon.find_ai_label("Photo: Northwind team, 2026")


def test_persona_name():
    assert lexicon.find_persona_name("Hi, I'm Sarah! How can I help?") == "Sarah"
    assert lexicon.find_persona_name("¡Hola! Soy Lucía, tu asistente virtual.") == "Lucía"
    assert lexicon.find_persona_name("I'm happy to help.") == ""
    assert lexicon.find_persona_name("I'm Sorry, that item is out of stock.") == ""


def test_vendor_detection():
    found = lexicon.detect_vendors('<script src="https://cdn.botpress.cloud/webchat/v2/inject.js">')
    assert [v.name for v in found] == ["Botpress"]
    assert lexicon.detect_vendors("", {"elevenlabs-convai"})[0].kind == "voice"
    assert lexicon.detect_vendors("https://example.com/app.js") == []
